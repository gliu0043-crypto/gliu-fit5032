test('batch review, selection limit and individual simulated delivery work without real email', async ({ page }) => {
  await organiser(page)
  const bulk = page.locator('.bulk-panel')
  await bulk.getByRole('button', { name: 'Review batch' }).click()
  await expect(bulk.getByText('Choose a recipient.', { exact: true })).toBeVisible()
  await audit(page, 'Invalid bulk form')
  await bulk.getByRole('button', { name: 'Select first 10 matching recipients' }).click()
  await expect(bulk.getByRole('checkbox', { checked: true })).toHaveCount(10)
  await expect(bulk.getByRole('checkbox').first()).toBeDisabled()
  await bulk.getByRole('button', { name: 'Clear selection' }).click()
  await bulk.getByRole('checkbox').nth(0).check()
  await bulk.getByRole('checkbox').nth(1).check()
  await bulk.getByLabel('Attachment', { exact: true }).setInputFiles({ name: 'activity.txt', mimeType: 'text/plain', buffer: Buffer.from('Local simulated attachment only.') })
  await bulk.getByRole('button', { name: 'Review batch' }).click()
  await expect(bulk.getByRole('heading', { name: 'Review 2 recipients' })).toBeFocused()
  await audit(page, 'Bulk review')
  await bulk.getByRole('button', { name: 'Confirm and send 2 emails' }).click()
  await expect(bulk.getByRole('heading', { name: 'Batch results' })).toBeVisible()
  await expect(bulk.getByText('Simulated — no email sent', { exact: false })).toHaveCount(2)
  await expect(bulk.getByRole('button', { name: 'Resume / check this batch' })).toHaveCount(0)
  await audit(page, 'Batch results')
})

