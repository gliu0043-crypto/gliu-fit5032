test('organiser export downloads all filtered records and readable PDF including Unicode', async ({ page }, testInfo) => {
  await organiser(page)
  const csv = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export CSV for activities' }).click()])
  const contents = await readFile(await csv[0].path(), 'utf8')
  expect(contents.split('\r\n').filter(Boolean)).toHaveLength(24)
  await page.getByLabel('Filter activities by suburb').fill('Clayton')
  const filtered = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export CSV for activities' }).click()])
  expect((await readFile(await filtered[0].path(), 'utf8')).split('\r\n').filter(Boolean)).toHaveLength(13)
  const pdf = await Promise.all([page.waitForEvent('download', { timeout: 45000 }), page.getByRole('button', { name: 'Export PDF for activities' }).click()])
  const pdfBytes = await readFile(await pdf[0].path())
  expect(pdfBytes.subarray(0, 5).toString()).toBe('%PDF-')
  await pdf[0].saveAs(testInfo.outputPath('activities-filtered.pdf'))
  // Exercise the same PDF exporter with Unicode and enough rows for multiple pages.
  const unicode = await Promise.all([page.waitForEvent('download'), page.evaluate(async () => {
    const { createPdf, downloadFile } = await import('/src/data/export.js')
    const table = { headers: ['Name', 'Activity'], body: Array.from({ length: 65 }, (_, i) => [`刘同学 ${i + 1}`, 'Community planting — 活动信息']) }
    downloadFile(await createPdf(table, 'Registrations'), 'unicode-registration-test.pdf')
  })])
  await unicode[0].saveAs(testInfo.outputPath('unicode-registration-test.pdf'))
  const registrationsPdf = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export PDF for registrations' }).click()])
  await registrationsPdf[0].saveAs(testInfo.outputPath('registrations.pdf'))
  await page.getByLabel('Filter activities by suburb').fill('no-such-suburb')
  await expect(page.getByRole('button', { name: 'Export PDF for activities' })).toBeDisabled()
})

